import Foundation

// swiftlint:disable line_length
extension EleventhReviewProbeSet {
    // markup in free text — elements that close themselves (the newest rule), property-list
    // keys, attributes in any order, and line breaks other than LF after them.

    func addMarkup() {
        section("n10-markup-selfclosing")
        p("<string name=\"password\" / >\n{S}")
        p("<string name=\"password\"/>\r\n{S}")
        p("<string name=\"password\"/>\n\n\n{S}")
        p("<string name=\"password\"/>\n  {S}")
        p("<string name=\"password\"/>\u{2028}{S}")
        p("<string name=\"password\"/>\u{85}{S}")
        p("<string name=\"password\"/><value>{S}</value>")
        p("<item name=\"\u{015E}ifre\"/>\n{S}")
        p("<item name=\"\u{24DF}\u{24D8}\u{24DD}\"/>\n{S}")
        p("<item key=\"api_key\"/>\n{S}")
        p("<item key=\"Pass\u{AD}word\"/>\n{S}")
        p("<item key=\"\(wild("password", [1, 6]))\"/>\n{S}")
        p("<STRING NAME=\"PASSWORD\"/>\n{S}")
        p("<string name='password'/>\n{S}")
        p("<string name=password />\n{S}")
        p("<string name=\"password\"/>\n<!--x-->{S}", claim: "D")        // next line starts with markup
        p("<string name=\"password\"></string>\n{S}", claim: "X")
        p("<string name=\"password\"/><!-- x -->\n{S}", claim: "X")

        section("n10-markup-plist")
        p("<key>password</key>\u{2028}<string>{S}</string>")
        p("<key>\u{015E}ifre</key>\n<string>{S}</string>")
        p("<key>\u{24DF}\u{24D8}\u{24DD}</key><integer>{S}</integer>")
        p("<dict><key>password</key><string>{S}</string></dict>")
        p("<key>password</key>\n<data/>\n{S}")
        p("<key>password</key><data/>\n{S}")
        p("<key>password</key>\n<data>\n{S}\n</data>")
        p("<key>pass&#119;ord</key><string>{S}</string>")
        p("<key>Pass\u{200C}word</key><string>{S}</string>")
        p("<key> api_key </key>\n\t<string>{S}</string>")
        p("<KEY>password</KEY><STRING>{S}</STRING>")

        // The key on its own line, as property lists are written: the empty element after it, then the value.
        section("n10-markup-plist-lines")
        p("<key>password</key>\n<string/>\n{S}")
        p("\t<key>password</key>\n\t<string/>\n\t{S}")
        p("<key>password</key>\n<string/> {S}")
        p("<key>password</key>\n<string/>{S}")
        p("<key>password</key>\n\n<string/>\n{S}")
        p("<key>api_key</key>\r\n<string />\r\n{S}")
        p("<key>\u{015E}ifre</key>\n<string/>\n{S}")
        p("<key>token</key>\n<data/> {S}")
        p("<key>password</key> <string/>\n{S}")                          // same line: control
        p("<key>password</key>\n<string></string>\n{S}", claim: "X")
        p("<string name=\"password\">\n</string>\n{S}", claim: "X")

        section("n10-markup-plist-lines-paths")
        p("{\"log\":\"<key>password</key>\\n<string/>\\n{S}\"}", json)
        p("<key>password</key>\n<string/>\n{S}", plain)
        p(multipart([part("note", "<key>password</key>\n<string/>\n{S}")]), mpType())
        p("note=%3Ckey%3Epassword%3C%2Fkey%3E%0A%3Cstring%2F%3E%0A{S}", form)
        p("{\"log\":\"name=[\\n\\\"pin\\\"\\n] {S}\"}", json)
        p("name=[\n\"pin\"\n] {S}", plain)

        section("n10-markup-attributes")
        p("<entry key=\"password\" value=\"{S}\"/>")
        p("<add key=\"ConnectionPassword\" value=\"{S}\" />")
        p("<add key=\"\u{015E}ifre\" value=\"{S}\" />")
        p("<input type=\"password\" value=\"{S}\">")
        p("<input value=\"{S}\" type=\"password\">")
        p("<input\n  value=\"{S}\"\n  type=\"password\">")
        p("<password>{S}</password>")
        p("<Password>\n  {S}\n</Password>")
        p("<param name=\"token\">{S}</param>")
        p("<meta name=\"csrf-token\" content=\"{S}\">")
        p("<string name=\"api_key\">\n{S}\n</string>")
        p("<setting name=\"Pass\u{301}word\" serializeAs=\"String\"><value>{S}</value></setting>")
    }

    // bodies — repeated keys, nesting, JSON in strings, forms with JSON, multipart headers,
    // malformed bodies, content types, and very large inputs.

    func addBodies() {
        section("n10-body-json")
        p("{\"password\":\"a\",\"pass\\u0077ord\":\"{S}\"}", json)
        p("{\"user\":{\"password\":\"x\"},\"user\":{\"password\":\"{S}\"}}", json)
        p("{\"a\":[[[[{\"pwd\":\"{S}\"}]]]]}", json)
        p("{\"a\":\"{\\\"b\\\":\\\"{\\\\\\\"token\\\\\\\":\\\\\\\"{S}\\\\\\\"}\\\"}\"}", json)
        p("{\"msg\":\"label=\u{015E}ifre&value={S}\"}", json)
        p("{\"msg\":\"{\\\"label\\\":\\\"\u{015E}ifre\\\",\\\"value\\\":\\\"{S}\\\"}\"}", json)
        p("{\"pass\\u0000word\":\"{S}\"}", json)
        p("{\"Password\":\"x\",\"password\":\"{S}\"}", json)
        p("{\"pin\":48291377}", json, secret: "48291377", width: 8)
        p("{\"note\":4111111111111111}", json, secret: "4111111111111111", digits: true)
        p("{\"note\":\"card 4111\\u00a01111\\u00a01111\\u00a01111\"}", json, secret: "4111111111111111", digits: true)
        p("[\"password\",\"{S}\"]", .body(nil))
        p("{\"\u{FF50}assword\":\"{S}\"}", .body(nil))

        section("n10-body-form")
        p("json=%7B%22password%22%3A%22{S}%22%7D", form)
        p("q=a%3D1%26password%3D{S}", form)
        p("password%00={S}", form)
        p("note=%22password%22+{S}", form)
        p("a=1&b=%7B%22x%22%3A%5B%7B%22token%22%3A%22{S}%22%7D%5D%7D", form)

        section("n10-body-multipart-header")
        p(multipart(["Content-Disposition: form-data; name=\"pass\\\"word\"\r\n\r\n{S}"]), mpType())
        p(multipart(["Content-Disposition: form-data; name*=UTF-8''password\r\n\r\n{S}"]), mpType())
        p(multipart(["Content-Disposition: form-data; name=\"x\"; name=\"password\"\r\n\r\n{S}"]), mpType())
        p(multipart(["Content-Disposition: form-data; name=password\r\n\r\n{S}"]), mpType())
        p(multipart(["Content-Disposition: FORM-DATA; NAME=\"password\"\r\n\r\n{S}"]), mpType())
        p(multipart(["Content-Disposition: form-data; name=\"pass%77ord\"\r\n\r\n{S}"]), mpType())
        p(multipart(["Content-Disposition: form-data; name=\"p&#97;ssword\"\r\n\r\n{S}"]), mpType())
        p(multipart(["Content-Disposition: form-data; name=\"password\"\r\nContent-Disposition: form-data; name=\"note\"\r\n\r\n{S}"]), mpType())
        p(multipart(["Content-Disposition: form-data;\r\n name=\"password\"\r\n\r\n{S}"]), mpType())
        p(multipart(["Content-Disposition: form-data; name=\"note\"\r\n\r\npassword={S}"]), mpType())
        p("password={S}\r\n" + multipart(["Content-Disposition: form-data; name=\"a\"\r\n\r\nx"]), mpType())
        p(multipart(["Content-Disposition: form-data; name=\"a\"\r\n\r\nx"]) + "\r\npassword={S}", mpType())
        p(multipart(["Content-Disposition: form-data; name=\"note\"\r\nContent-Type: text/x-secret\r\n\r\n{S}"]), mpType())
        p(multipart(["Content-Disposition: form-data; name=\"note\"\r\nContent-Type: application/json\r\n\r\n{password:{S}}"]), mpType())
        p(multipart(["Content-Disposition: form-data; name=\"note\"\r\nContent-Transfer-Encoding: quoted-printable\r\n\r\npassword=3D{S}"]), mpType())
        p(multipart(["Content-Disposition: form-data; name=\"note\"\r\nContent-Transfer-Encoding: 8bit\r\nContent-Transfer-Encoding: base64\r\n\r\n{S}"]), mpType())
        p(multipart(["Content-Disposition: form-data; name=\"note\"\r\nX-Secret: {S}\r\n\r\nhi"]), mpType())
        p(multipart(["Content-Disposition: form-data; name=\"note\"; filename=\"a.txt\"\r\n\r\npassword={S}"]), mpType())
        p(multipart(["Content-Disposition: form-data; name=\"doc\"; filename*=UTF-8''a.txt\r\n\r\npassword={S}"]), mpType())
        p(multipart(["Content-Disposition: form-data; name=\"token\"\r\n\r\n{S}"], boundary: "b-\u{2028}"), mpType("b-\u{2028}"))
        p(multipart(["Content-Disposition: form-data; name=\"note\"\r\n\r\nhi\r\n--b0UND\r\nContent-Disposition: form-data; name=\"password\"\r\n\r\n{S}"]), mpType())

        section("n10-body-malformed")
        p("\u{FEFF}{\"password\":\"{S}\"}", json)
        p("{\"password\":\"{S}\"} trailing", json)
        p("{\"password\":\"{S}\" /* c */}", json)
        p("{\"a\":\"\\uD800\",\"password\":\"{S}\"}", json)
        p("{\"password\":\"{S}\",\"n\":NaN}", json)
        p("{\"password\":\"{S}\",}", json)
        p("{'password':'{S}'}", json)
        p("{password:\"{S}\"}", json)
        p("password={S};x=1", form)
        p("password={S}&bad=%G1", form)
        p("p\u{E4}ssword={S}", form)
        p("pass word={S}", form)
        p("password={S}", .bytes([0xFF, 0xFE], "text/plain"))
        p("{\"password\":\"{S}\"}", .encoded(.utf16, "application/json; charset=utf-16"))
        p("{\"password\":\"{S}\"}", .body("Application/JSON"))
        p("{\"password\":\"{S}\"}", .body("application/json, text/plain"))
        p("{\"password\":\"{S}\"}", .body("application/vnd.api+json"))
        p("{\"password\":\"{S}\"}", .body("text/json"))
        p("{\"password\":\"{S}\"}", .body("application/json;charset=\"utf-8\""))
        p("{\"password\":\"{S}\"}", .body("application/json; charset=utf-8; charset=latin1"))
        p("{\"password\":\"{S}\"}", .body("application/json ; charset=utf-8"))
        p("password={S}", .body("application/x-www-form-urlencoded; charset=utf-8"))
        p(multipart(["Content-Disposition: form-data; name=\"password\"\r\n\r\n{S}"]), .body("multipart/form-data; boundary=\"B0und\""))
        p(multipart(["Content-Disposition: form-data; name=\"password\"\r\n\r\n{S}"]), .body("multipart/form-data; boundary=B0und; boundary=X"))
        p(multipart(["Content-Disposition: form-data; name=\"password\"\r\n\r\n{S}"]), .body("multipart/mixed; boundary=B0und"))
        p("password={S}", .body(nil))
        p("\"password {S}\"", .body(nil))
        p("password {S}", .body("text/html"))
        p("<password>{S}</password>", .body("application/xml"))

        section("n10-body-large")
        let filler = String(repeating: "a", count: 1_048_576)
        p("{\"x\":\"\(filler)\",\"password\":\"{S}\"}", json)
        let nearly = String(repeating: "b", count: 1_048_400)
        p("{\"x\":\"\(nearly)\",\"password\":\"{S}\"}", json)
        p(String(repeating: "word ", count: 400_000) + "password {S}")
        p(String(repeating: "x", count: 500_000) + " password {S}")
        let manyFields = (0..<20_000).map { "{\"k\($0)\":\($0)}" }.joined(separator: ",")
        p("[\(manyFields),{\"password\":\"{S}\"}]", json)
        p(String(repeating: "[", count: 63) + "{\"password\":\"{S}\"}" + String(repeating: "]", count: 63), json)
        p("{\"note\":\"" + String(repeating: "[", count: 70) + String(repeating: "]", count: 70) + " password {S}\"}", json)
        p(String(repeating: "a=1&", count: 50_000) + "password={S}", form)
        p(multipart((0..<1_000).map { "Content-Disposition: form-data; name=\"f\($0)\"\r\n\r\nv" } + ["Content-Disposition: form-data; name=\"password\"\r\n\r\n{S}"]), mpType())
        p(String(repeating: "{\"a\":", count: 70) + "\"password {S}\"" + String(repeating: "}", count: 70))
        p("https://x.example/" + String(repeating: "a/", count: 70) + "password/{S}", .url)
        p("https://x.example/a?" + String(repeating: "x=1&", count: 130) + "token={S}", .urlAllowing(["x", "token"]))
    }
}
