        p("{\"label\":\"Your password, please\",\"value\":\"{S}\"}", json, claim: "X")
        p("{\"fields\":[{\"label\":\"Password\"},{\"value\":\"{S}\"}]}", json, claim: "X")
        p("{\"label\":{\"en\":\"Password\"},\"value\":\"{S}\"}", json, claim: "X")
        p("{\"label\":[\"Password\"],\"value\":\"{S}\"}", json, claim: "X")
        p("{\"label\":\"\u{41F}\u{430}\u{440}\u{43E}\u{43B}\u{44C}\",\"value\":\"{S}\"}", json, claim: "X")

        section("n9-json-pairs-arrays")
        p("{\"headers\":[[\"Authorization\",\"{S}\"]]}", json)
        p("{\"h\":[[\"X-Api-Key\",\"{S}\"]]}", json)
        p("[\"user\",\"bob\",\"password\",\"{S}\"]", json)
        p("[\"Password:\",\"{S}\"]", json)
        p("[\"pass word\",\"{S}\"]", json)
        p("[\"\u{41F}\u{430}\u{440}\u{43E}\u{43B}\u{44C}\",\"{S}\"]", json)
        p("[[\"x-api-k\u{435}y\",\"{S}\"]]", json)
        p("{\"entries\":[{\"name\":\"X-Auth-Token\",\"value\":\"{S}\"}]}", json)
        p("{\"entries\":[{\"name\":\"X-Auth\u{2010}Token\",\"value\":\"{S}\"}]}", json)
        p("{\"a\":[{\"b\":[{\"c\":{\"api_key\":\"{S}\"}}]}]}", json)
        p("{\"\u{24DF}\u{24D0}\u{24E2}\u{24E2}\u{24E6}\u{24DE}\u{24E1}\u{24D3}\":\"{S}\"}", json)
