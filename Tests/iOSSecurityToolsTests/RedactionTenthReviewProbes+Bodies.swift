    // JSON objects that name a secret in a member's value, pairs, arrays, repeated keys,
    // nesting and JSON inside strings.
    func addJSON() {
        section("n9-json-naming-member")
        p("{\"label\":\"\u{3A1}assword\",\"value\":\"{S}\"}", json)
        p("{\"label\":\"\u{24E3}\u{24DE}\u{24DA}\u{24D4}\u{24DD}\",\"input\":\"{S}\"}", json)
        p("{\"label\":\"\u{1D683}\u{1D698}\u{1D694}\u{1D68E}\u{1D697}\",\"value\":\"{S}\"}", json)
        p("{\"label\":\"\u{FF21}\u{FF30}\u{FF29} \u{FF2B}\u{FF45}\u{FF59}\",\"value\":\"{S}\"}", json)
        p("{\"label\":\"Pass\u{200B}word\",\"value\":\"{S}\"}", json)
        p("{\"label\":\"Pass\\u200bword\",\"value\":\"{S}\"}", json)
        p("{\"label\":\"\\ufefftoken\",\"value\":\"{S}\"}", json)
        p("{\"label\":\"Pa\\u0335ssword\",\"value\":\"{S}\"}", json)
        p("{\"label\":\"pass\\u0077ord\",\"value\":\"{S}\"}", json)
        p("{\"label\":\"pass%77ord\",\"value\":\"{S}\"}", json)
        p("{\"label\":\"pass&#119;ord\",\"value\":\"{S}\"}", json, claim: "X")    // `;` makes it a sentence
        p("{\"label\":\"P-a-s-s-w-o-r-d\",\"value\":\"{S}\"}", json)
        p("{\"label\":\"Password:\",\"value\":\"{S}\"}", json)
        p("{\"label\":\"Password *\",\"value\":\"{S}\"}", json)
        p("{\"label\":\"Enter your password\",\"value\":\"{S}\"}", json)
        p("{\"label\":\"Password #2\",\"value\":\"{S}\"}", json)
        p("{\"label\":\"PIN\",\"value\":73914862}", json, secret: "739148")
        p("{\"label\":\"PIN\",\"value\":[\"{S}\"]}", json)
        p("{\"label\":\"PIN\",\"value\":{\"a\":{\"b\":\"{S}\"}}}", json)
        p("{\"label\":\"Password\",\"value\":\"x\",\"extra\":\"{S}\"}", json)
        p("{\"value\":\"{S}\",\"label\":\"Password\"}", json)
        p("{\"Name\":\"PASSWORD\",\"Value\":\"{S}\"}", json)
        p("{\"ParameterKey\":\"DbPassword\",\"ParameterValue\":\"{S}\"}", json)
        p("{\"type\":\"password\",\"name\":\"pw\",\"value\":\"{S}\"}", json)
        p("{\"op\":\"test\",\"path\":\"/password\",\"value\":\"{S}\"}", json)
        p("[{\"op\":\"replace\",\"path\":\"/credentials/0/secret\",\"value\":\"{S}\"}]", json)
        p("[{\"op\":\"add\",\"path\":\"/users/0/pin\",\"value\":{\"v\":\"{S}\"}}]", json)
        p("{\"op\":\"replace\",\"path\":\"/p\u{430}ssword\",\"value\":\"{S}\"}", json)
        p("{\"op\":\"replace\",\"path\":\"/pass~1word\",\"value\":\"{S}\"}", json)
        p("{\"op\":\"Replace\",\"label\":\"Password\",\"value\":\"{S}\"}", json)
        p("{\"label\":\"Password\",\"op\":\"{S}\"}", json)
        p("{\"label\":\"Password\",\"path\":\"{S}\"}", json, claim: "D")              // a member that holds a name stays
        p("{\"label\":\"Password\",\"field\":\"{S}\"}", json, claim: "D")
