        p("payload=\"{\\\"password\\\":\\\"{S}\\\"}\"")
        p("status={\\\"token\\\":\\\"{S}\\\"}")
        p("status=200 body={\"label\":\"Password\",\"value\":\"{S}\"}")
        p("status=200 {\"label\":\"P\u{430}ssword\",\"value\":\"{S}\"} done")
    }

    func n9part(_ name: String, _ value: String, extra: String = "") -> String {
        "Content-Disposition: form-data; name=\"\(name)\"\(extra)\r\n\r\n\(value)"
    }

    // Form and JSON mixes, multipart headers, broken and large bodies.
    func addBodies() {
        section("n9-form-json-mix")
        p("password={S}&a=1", json)
        p("{\"password\":\"{S}\"}", form)
        p("json={\"token\":\"{S}\"}", form)
        p("a=1&b={\"x\":[{\"pin\":\"{S}\"}]}", form)
        p("user=bob&p%61ssword={S}", form)
        p("creds[password]={S}", form)
        p("user=bob&=&password={S}", form)
        p("a=1&&password=%7B{S}%7D", form)
        p("data=%7B%22label%22%3A%22Password%22%2C%22value%22%3A%22{S}%22%7D", form)
        p("data=%7B%22password%22%3A%22{S}%22%7D", form)
        p("note=%5B%22Authorization%22%2C%22{S}%22%5D", form)
        p("\u{FF50}\u{FF41}\u{FF53}\u{FF53}\u{FF57}\u{FF4F}\u{FF52}\u{FF44}={S}", form)
        p("pass%C2%ADword={S}", form)
        p("pass%E2%80%8Dword={S}", form)
        p("pa%CC%81ssword={S}", form)
        p("label=Password&value={S}", form, claim: "X")                     // a form pair written as two fields

        section("n9-multipart-header")
        p(multipart([n9part("pass\\\"word", "{S}")]), mpType())
        p(multipart(["Content-Disposition: form-data; name*=UTF-8''pass%77ord\r\n\r\n{S}"]), mpType())
        p(multipart(["Content-Disposition: form-data; name=\"note\"\r\nX-Api-Key: {S}\r\n\r\nok"]), mpType())
        p(multipart(["Content-Disposition: form-data; NAME=\"token\"\r\n\r\n{S}"]), mpType())
        p(multipart(["Content-Disposition: form-data;\r\n name=\"password\"\r\n\r\n{S}"]), mpType())
        p(multipart([n9part("pin", "{S}")]), .body("multipart/form-data; boundary=\"B0und\""))
        p(multipart(["Content-Disposition: form-data; name=\"blob\"\r\nContent-Type: application/json\r\n\r\n{\"token\":\"{S}\"}"]), mpType())
        p(multipart(["Content-Disposition: form-data; name=\"blob\"\r\nContent-Type: application/json\r\n\r\n{\"label\":\"Password\",\"value\":\"{S}\"}"]), mpType())
        p(multipart([n9part("note", "<string name=\"api_key\">{S}</string>")]), mpType())
        p(multipart([n9part("p\u{430}ssword", "{S}")]), mpType())
        p(multipart([n9part("pass\u{200D}word", "{S}")]), mpType())
        p(multipart([n9part("pin", "{S}", extra: "; filename=\"a.txt\"")]), mpType())
        p(multipart([n9part("note", "x"), n9part("note", "password\u{2028}{S}")]), mpType())
        p("--B0und\nContent-Disposition: form-data; name=\"pin\"\n\n{S}\n--B0und--", mpType())
        p(multipart(["Content-Disposition: form-data; name=\"ok\"; name=\"pin\"\r\n\r\n{S}"]), mpType())

        section("n9-broken-body")
        p("{\"password\":\"{S}", json)
        p("{\"a\":1}{\"password\":\"{S}\"}", json)
        p("{/*x*/\"password\":\"{S}\"}", json)
        p("{'password':'{S}'}", json)
        p("{\"a\":NaN,\"token\":\"{S}\"}", json)
        p("{\"password\":\"{S}\"}", .bytes([0xFF], "application/json"))
        p("{\"password\":\"{S}\"}", .bytes([0xEF, 0xBB, 0xBF], "application/json"))
        p("{\"pass\\u0000word\":\"{S}\"}", json)
        p("password {S}", json)
        p("{\"password\":\"{S}\"}", .encoded(.utf16, "application/json"))
        p("{\"label\":\"Password\",\"value\":\"{S}\"}", .encoded(.utf16, "application/json; charset=utf-16"))
        p("password={S}", .body(nil))
        p("{\"label\":\"Password\",\"value\":\"{S}\"}", .body("application/vnd.api+json"))
        p("{\"label\":\"Password\",\"value\":\"{S}\"}", .body("text/plain"))
        p("{\"label\":\"Password\",\"value\":\"{S}\",}", json)
        p("{\"label\":\"Password\",\"value\":\"{S}\"}", .bytesAfter([0x00], "application/json"))
        p("{\"label\":\"Password\",\"value\":\"{S}\"\n", json)

        section("n9-large")
        let mib = SensitiveDataRedactor.maximumBodySize
        p(String(repeating: " ", count: mib - 60) + "{\"label\":\"Password\",\"value\":\"{S}\"}", json)
        p("[" + String(repeating: "{\"label\":\"Status\",\"value\":\"ok\"},", count: 20_000) + "{\"label\":\"Password\",\"value\":\"{S}\"}]", json)
        p(String(repeating: "a ", count: 200_000) + "name=\"password\" {S}")
        p(String(repeating: "status=200\n", count: 100_000) + "<key>password</key>\n<string>{S}</string>")
        p(String(repeating: "[", count: 64) + "\"password\",\"{S}\"" + String(repeating: "]", count: 64), json)
        p(String(repeating: "[", count: 65) + "\"password\",\"{S}\"" + String(repeating: "]", count: 65), json)
        p(String(repeating: "{\"a\":", count: 70) + "{\"label\":\"Password\",\"value\":\"{S}\"}" + String(repeating: "}", count: 70))
    }
}
