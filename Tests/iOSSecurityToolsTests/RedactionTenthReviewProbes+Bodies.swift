        p("{\"user\":\"bob\",\"Pass Word\":\"{S}\"}", json)

        section("n9-json-repeated")
        p("{\"password\":\"x\",\"password\":\"{S}\"}", json)
        p("{\"a\":{\"token\":\"x\"},\"a\":{\"token\":\"{S}\"}}", json)
